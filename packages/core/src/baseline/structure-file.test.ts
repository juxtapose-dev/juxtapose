import { mkdtemp, readFile, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { expect, test } from 'vitest';
import type { StructureSnapshot } from '../types.js';
import type { ComponentSnapshot } from '../components/evidence.js';
import {
  compactStructure,
  formatCompactStructure,
  structureFile,
  expandStructure,
  readStructureFile,
  writeStructureFile,
} from './structure-file.js';
import { CacheBaselineStore } from './cache-store.js';
const elements = [
  { path: 'html>body>main', parent: null },
  { path: 'html>body>main>div.skipped>button', parent: 0 },
  { path: 'html>body>main>div.skipped>button::before', parent: 1 },
  { path: 'html>body>aside', parent: null },
];
const snapshot: StructureSnapshot = {
  schema: 'juxtapose.structure/v1',
  structureHash: 'a'.repeat(64),
  viewport: { width: 100, height: 100 },
  contentHeight: 100,
  elements: elements.map(
    (e, i) =>
      ({
        ...e,
        tag: 'div',
        rect: { x: 0, y: 0, w: 10, h: 10 },
        paintOrder: i,
        styles: {},
        text: 'hello',
        external: [{ kind: 'image', origin: 'https://example.com', path: '/a' }],
      }) as StructureSnapshot['elements'][number],
  ),
};

test('relative paths retain omitted ancestors and absolute fallback, with exact evidence roundtrip', () => {
  const compact = compactStructure(snapshot);
  expect(compact.elements[1]).toHaveProperty('segment', 'div.skipped>button');
  expect(compact.elements[2]).toHaveProperty('path', elements[2]!.path);
  expect(expandStructure(compact)).toEqual(snapshot);
  compact.elements[1]!.parent = 1;
  expect(() => expandStructure(compact)).toThrow('invalid structure parent');
});

test('compact saved evidence preserves v3 grid capabilities and measured areas', () => {
  const captured = structuredClone(snapshot);
  captured.styleCaptureVersion = 3;
  captured.elements[0]!.styles['grid-template-areas'] = '"main badge" "meta action"';
  expect(expandStructure(compactStructure(captured))).toEqual(captured);
});

test('files are readable, checksum-bound, and referenced from a small annotated manifest', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'jux-structure-'));
  try {
    const store = new CacheBaselineStore({ projectRoot: root });
    await store.put('button--basic', Buffer.from('image'), {
      commit: 'abc',
      approvedBy: 'test',
      approvedAt: 'now',
    });
    await store.putStructure('button--basic', Buffer.from(JSON.stringify(snapshot)));
    const manifest = await store.readManifest();
    expect(manifest.$comment).toContain('Generated by Juxtapose');
    const entry = manifest.baselines['button--basic']!;
    expect(entry.structure).toBeUndefined();
    expect(JSON.parse((await store.getStructure('button--basic'))!.toString())).toEqual(
      snapshot,
    );
    const file = path.join(root, entry.structureFile!);
    expect(JSON.parse(await readFile(file, 'utf8')).elements[1].segment).toBe(
      'div.skipped>button',
    );
    expect(
      await readFile(path.join(root, 'juxtapose.structures/README.md'), 'utf8'),
    ).toContain('jux approve');
    await writeFile(file, (await readFile(file, 'utf8')).replace('hello', 'wrong'));
    expect(await store.getStructure('button--basic')).toBeNull();
    expect((await store.readManifest()).baselines['button--basic']!.hash).toBe(
      entry.hash,
    );
    expect(
      await readStructureFile(root, 'button--basic', {
        ...entry,
        structureFile: '../outside.json',
      }),
    ).toBeNull();
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('migration preserves inline evidence and approval metadata without recapture', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'jux-structure-'));
  try {
    const { structureHash, ...structure } = snapshot;
    const entry = {
      hash: 'b'.repeat(64),
      commit: 'abc',
      approvedBy: 'test',
      approvedAt: 'now',
      structureHash,
      structure,
    };
    await writeFile(
      path.join(root, 'juxtapose.manifest.json'),
      JSON.stringify({ version: 1, baselines: { a: entry } }),
    );
    const store = new CacheBaselineStore({ projectRoot: root });
    expect(JSON.parse((await store.getStructure('a'))!.toString())).toEqual(snapshot);
    expect(await store.migrateLegacyStructures()).toEqual({ migrated: 1, skipped: [] });
    const migrated = (await store.readManifest()).baselines.a!;
    expect(migrated).toMatchObject({
      hash: entry.hash,
      commit: entry.commit,
      approvedBy: entry.approvedBy,
      approvedAt: entry.approvedAt,
      structureHash,
    });
    expect(migrated.structure).toBeUndefined();
    expect(JSON.parse((await store.getStructure('a'))!.toString())).toEqual(snapshot);
    expect(await store.migrateLegacyStructures()).toEqual({ migrated: 0, skipped: [] });
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('a linked structure directory cannot write outside the project', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'jux-structure-'));
  const outside = await mkdtemp(path.join(tmpdir(), 'jux-outside-'));
  try {
    await symlink(outside, path.join(root, 'juxtapose.structures'));
    await expect(writeStructureFile(root, 'a', snapshot)).rejects.toThrow(
      'real directory',
    );
  } finally {
    await rm(root, { recursive: true, force: true });
    await rm(outside, { recursive: true, force: true });
  }
});

test('removing structure on a new approval cannot resurrect a legacy sidecar', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'jux-structure-'));
  try {
    const { mkdir } = await import('node:fs/promises');
    await mkdir(path.join(root, '.juxtapose/baselines'), { recursive: true });
    await writeFile(path.join(root, '.juxtapose/baselines/a.webp'), 'old');
    await writeFile(
      path.join(root, '.juxtapose/baselines/a.structure.json.gz'),
      JSON.stringify(snapshot),
    );
    const store = new CacheBaselineStore({ projectRoot: root });
    await store.put('a', Buffer.from('new'), {
      commit: 'abc',
      approvedBy: 'test',
      approvedAt: 'now',
    });
    expect(await store.getStructure('a')).toBeNull();
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('filenames remain distinct on case-insensitive filesystems and stay inside the directory', () => {
  expect(structureFile('Button').toLowerCase()).not.toBe(
    structureFile('button').toLowerCase(),
  );
  expect(structureFile('con')).not.toBe('juxtapose.structures/con.json');
  expect(structureFile('../outside')).not.toContain('../');
  expect(path.basename(structureFile('x'.repeat(300))).length).toBeLessThan(255);
});

test('inline migration and capture field order produce identical file bytes', () => {
  const { structureHash, ...inline } = snapshot;
  expect(formatCompactStructure({ ...inline, structureHash })).toEqual(
    formatCompactStructure(snapshot),
  );
});

test('compact and saved baselines retain sanitized components without changing structureHash', async () => {
  const components: ComponentSnapshot = {
    schema: 'juxtapose.components/v1',
    trees: [
      {
        framework: 'vue',
        parentRelation: 'rendered-parent',
        elementRelation: 'rendered-by',
        coverage: 'runtime',
        status: 'available',
        truncated: false,
        nodes: [{ id: 0, parent: null, name: 'Card', elements: [0, 1] }],
      },
    ],
  };
  const enriched: StructureSnapshot = { ...snapshot, components };
  expect(expandStructure(compactStructure(enriched))).toEqual(enriched);
  const root = await mkdtemp(path.join(tmpdir(), 'jux-component-baseline-'));
  try {
    const receipt = await writeStructureFile(root, 'card--default', enriched);
    const bytes = await readStructureFile(root, 'card--default', {
      ...receipt,
      structureHash: snapshot.structureHash,
      hash: 'b'.repeat(64),
      commit: 'test',
      approvedBy: 'test',
      approvedAt: '2026-11-01T00:00:00Z',
    });
    expect(bytes).not.toBeNull();
    expect(JSON.parse(bytes!.toString('utf8'))).toEqual(enriched);
    expect(JSON.parse(bytes!.toString('utf8')).structureHash).toBe(
      snapshot.structureHash,
    );
  } finally {
    await rm(root, { recursive: true, force: true });
  }
  const malformed = compactStructure(enriched);
  Object.assign(malformed.components!.trees[0]!.nodes[0]!, { parent: 0 });
  expect(expandStructure(malformed)).toEqual(snapshot);
});
